"""One-off (plan steps 3b, 3b2): golden.json's fromisoformat cases to web/src/modules/listings/legacy-time.fixtures.json.
Run from web/: python3 ../docs/plans/2026-11-15-self-hosted-rebuild/step-3b/convert-fromisoformat.py
Every case keeps Python's result (3b2: the legacy parser matches fromisoformat in full)."""
import datetime as dt
import json

g = json.load(open('tests/fixtures/golden.json'))
cases = []
for c in g['fromisoformat']:
    i, e = c['input'], c['expect']
    if 'error' in e:
        cases.append({'input': i, 'expect': None})
        continue
    y, mo, d, h, mi, s, us, off = e['ok']
    ms = us // 1000
    if off is None:
        if (h, mi, s, us) == (0, 0, 0, 0) and len(i) <= 10:
            exp = {'kind': 'date', 'year': y, 'month': mo, 'day': d}
        else:
            exp = {'kind': 'naive', 'utcIfAssumed': dt.datetime(y, mo, d, h, mi, s, ms * 1000).isoformat(timespec='milliseconds') + 'Z'}
    else:
        t = dt.datetime(y, mo, d, h, mi, s, us, tzinfo=dt.timezone.utc) - dt.timedelta(microseconds=off)
        exp = {'kind': 'aware', 'instant': t.strftime('%Y-%m-%dT%H:%M:%S.') + f'{t.microsecond // 1000:03d}Z'}
    cases.append({'input': i, 'expect': exp})
out = {'about': 'Native cases of golden.json fromisoformat for the legacy parser (plan steps 3b, 3b2; generated by docs/plans/2026-11-15-self-hosted-rebuild/step-3b/convert-fromisoformat.py). expect null is refused. Instants keep milliseconds (JavaScript Date); Python kept microseconds.', 'cases': cases}
with open('src/modules/listings/legacy-time.fixtures.json', 'w') as f:
    json.dump(out, f, ensure_ascii=False, indent=1)
print(len(cases), 'cases')
