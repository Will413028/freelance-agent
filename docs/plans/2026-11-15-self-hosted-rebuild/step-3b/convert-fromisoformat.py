"""One-off (plan step 3b): golden.json's fromisoformat cases to web/src/modules/evaluation/time.fixtures.json.
Run from web/: python3 ../docs/plans/2026-11-15-self-hosted-rebuild/step-3b/convert-fromisoformat.py
A case Python accepted and the native parser refuses on purpose carries `change` and Python's result."""
import datetime as dt
import json

g = json.load(open('tests/fixtures/golden.json'))
cases = []
for c in g['fromisoformat']:
    i, e = c['input'], c['expect']
    if 'error' in e:
        cases.append({'input': i, 'expect': None})
        continue
    y, mo, d, h, mi, s, us, off = e['ok']
    rej = None
    if 'W' in i:
        rej = 'ISO week date: native reads calendar dates only'
    elif i == '2026-09-17T10:00:00:12':
        rej = 'a fourth time field: Python read :12 as a fraction, native refuses it'
    elif len(i) > 10 and i[10] not in 'T ' and i[:4].isdigit() and i[4] == '-':
        rej = 'date and time joined by a character other than T or a space'
    if rej:
        cases.append({'input': i, 'expect': None, 'python': e['ok'], 'change': rej})
        continue
    ms = us // 1000
    if off is None:
        if i in (f'{y:04d}-{mo:02d}-{d:02d}', f'{y:04d}{mo:02d}{d:02d}'):
            exp = {'kind': 'date', 'year': y, 'month': mo, 'day': d}
        else:
            exp = {'kind': 'naive', 'utcIfAssumed': dt.datetime(y, mo, d, h, mi, s, ms * 1000).isoformat(timespec='milliseconds') + 'Z'}
    else:
        t = dt.datetime(y, mo, d, h, mi, s, us, tzinfo=dt.timezone.utc) - dt.timedelta(microseconds=off)
        exp = {'kind': 'aware', 'instant': t.strftime('%Y-%m-%dT%H:%M:%S.') + f'{t.microsecond // 1000:03d}Z'}
    cases.append({'input': i, 'expect': exp})
out = {'about': 'Native cases of golden.json fromisoformat (plan step 3b; generated by docs/plans/2026-11-15-self-hosted-rebuild/step-3b/convert-fromisoformat.py). expect null is refused; a case with change was accepted by Python (its result in python) and is refused natively for that reason. Instants keep milliseconds (JavaScript Date); Python kept microseconds.', 'cases': cases}
with open('src/modules/evaluation/time.fixtures.json', 'w') as f:
    json.dump(out, f, ensure_ascii=False, indent=1)
print(sum(1 for c in cases if 'change' in c), 'changed of', len(cases))
